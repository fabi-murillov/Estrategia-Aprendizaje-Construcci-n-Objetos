public class Suscripcion {
    //Atributos
    String tipo;
    double costo;
    int periodicidad;

    //Métodos
    //Constructor completo
    Suscripcion(String tipo, double costo, int periodicidad) {
        this.tipo = tipo;
        this.costo = costo;
        this.periodicidad = periodicidad;
    }

}
